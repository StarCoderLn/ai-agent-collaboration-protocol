-- 回滚只允许在没有业务资金数据时执行；否则把 USDC 最小单位重新解释成 wei 会造成
-- 严重金额错误。该保护比“勉强可回滚”更重要，真实恢复应使用迁移前数据库快照。
BEGIN;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM tasks) OR EXISTS (SELECT 1 FROM escrow_intents) THEN
    RAISE EXCEPTION 'USDC_MIGRATION_ROLLBACK_REQUIRES_EMPTY_MONEY_DATA';
  END IF;
  IF EXISTS (
    SELECT 1 FROM agents
     WHERE id NOT IN (
       '91000000-0000-4000-8000-000000000001',
       '91000000-0000-4000-8000-000000000002',
       '91000000-0000-4000-8000-000000000003',
       '91000000-0000-4000-8000-000000000004',
       '91000000-0000-4000-8000-000000000005',
       '91000000-0000-4000-8000-000000000006',
       '91000000-0000-4000-8000-000000000007',
       '91000000-0000-4000-8000-000000000008',
       '91000000-0000-4000-8000-000000000009'
     )
  ) THEN
    RAISE EXCEPTION 'USDC_MIGRATION_ROLLBACK_REQUIRES_ONLY_BUILTIN_AGENTS';
  END IF;
END $$;

ALTER TABLE escrow_intents RENAME COLUMN amount_minor TO amount_wei;
ALTER TABLE escrow_sync RENAME COLUMN amount_minor TO amount_wei;
ALTER TABLE escrow_execution_jobs RENAME COLUMN agent_gross_amount_minor TO agent_gross_amount_wei;
ALTER TABLE escrow_execution_jobs RENAME COLUMN fee_amount_minor TO fee_amount_wei;
ALTER TABLE tasks ALTER COLUMN currency SET DEFAULT 'ETH';

UPDATE platform_fee_config SET active = FALSE WHERE active = TRUE;
UPDATE platform_fee_config SET active = TRUE WHERE version = 'fee-v2-native-eth';
DELETE FROM platform_fee_config WHERE version = 'fee-v3-usdc';

UPDATE agents
   SET price_currency = 'ETH',
       price_amount = CASE id
         WHEN '91000000-0000-4000-8000-000000000001' THEN 1200000000000000
         WHEN '91000000-0000-4000-8000-000000000002' THEN 1800000000000000
         WHEN '91000000-0000-4000-8000-000000000003' THEN 2400000000000000
         WHEN '91000000-0000-4000-8000-000000000004' THEN 1600000000000000
         WHEN '91000000-0000-4000-8000-000000000005' THEN 2200000000000000
         WHEN '91000000-0000-4000-8000-000000000006' THEN 2800000000000000
         WHEN '91000000-0000-4000-8000-000000000007' THEN 2400000000000000
         WHEN '91000000-0000-4000-8000-000000000008' THEN 3200000000000000
         WHEN '91000000-0000-4000-8000-000000000009' THEN 4200000000000000
         ELSE price_amount
       END
 WHERE id IN (
   '91000000-0000-4000-8000-000000000001',
   '91000000-0000-4000-8000-000000000002',
   '91000000-0000-4000-8000-000000000003',
   '91000000-0000-4000-8000-000000000004',
   '91000000-0000-4000-8000-000000000005',
   '91000000-0000-4000-8000-000000000006',
   '91000000-0000-4000-8000-000000000007',
   '91000000-0000-4000-8000-000000000008',
   '91000000-0000-4000-8000-000000000009'
 );

-- 回滚仅恢复旧版结构约束；生产恢复仍必须使用迁移前快照，不能依赖本文件换算资产。
ALTER TABLE agents DROP CONSTRAINT agents_price_amount_check;
ALTER TABLE agents ADD CONSTRAINT agents_price_amount_check CHECK (price_amount >= 0);

COMMIT;
